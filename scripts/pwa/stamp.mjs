// Generates sw-precache.js: the service worker's file list and the content hashes that name its caches.
// Run `npm run pwa:stamp` after changing any file below. `npm run check` (and CI) fails if the stamp is stale,
// so a shipped file can never be served from an out-of-date offline cache.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

// URL -> file on disk. Core files are cached at install: the whole app shell, a few MB at most.
export const CORE = {
  '/': 'index.html',
  '/privacy': 'privacy.html',
  '/offline.html': 'offline.html',
  '/manifest.webmanifest': 'manifest.webmanifest',
  '/assets/arah-enhancements.js': 'assets/arah-enhancements.js',
  '/assets/arah-pwa.js': 'assets/arah-pwa.js',
  '/assets/places/arah-places.js': 'assets/places/arah-places.js',
  '/assets/places/places-core.mjs': 'assets/places/places-core.mjs',
  '/assets/places/brands.mjs': 'assets/places/brands.mjs',
  '/assets/ar/arah-ar.js': 'assets/ar/arah-ar.js',
  '/assets/ar/ar-core.mjs': 'assets/ar/ar-core.mjs',
  '/assets/ar/ar-engine.mjs': 'assets/ar/ar-engine.mjs',
  '/assets/ar/ar-worker.js': 'assets/ar/ar-worker.js',
  '/assets/icons/icon-192.png': 'assets/icons/icon-192.png',
  '/assets/icons/icon-512.png': 'assets/icons/icon-512.png',
  '/assets/icons/icon-maskable-512.png': 'assets/icons/icon-maskable-512.png',
  '/assets/icons/apple-touch-icon.png': 'assets/icons/apple-touch-icon.png',
  '/assets/icons/favicon-48.png': 'assets/icons/favicon-48.png',
};
// Cached the first time AR is used (4 MB): not worth downloading for people who never turn AR on.
export const LAZY = {
  '/assets/ar/vendor/ort.webgl.min.js': 'assets/ar/vendor/ort.webgl.min.js',
  '/assets/ar/models/yolox_nano.onnx': 'assets/ar/models/yolox_nano.onnx',
};

const digest = (map) => createHash('sha256').update(
  Object.entries(map).map(([url, file]) => `${url}\0${createHash('sha256').update(readFileSync(join(ROOT, file))).digest('hex')}`).join('\n'),
).digest('hex').slice(0, 12);

export function build() {
  const release = JSON.parse(readFileSync(join(ROOT, 'versions.json'), 'utf8')).release;
  return { release, core: Object.keys(CORE), lazy: Object.keys(LAZY), coreHash: digest(CORE), lazyHash: digest(LAZY) };
}

export function render(b) {
  return `// Generated by scripts/pwa/stamp.mjs. Do not edit; run \`npm run pwa:stamp\`.\n` +
    `self.__ARAH_PRECACHE = ${JSON.stringify(b, null, 2)};\n`;
}

const out = join(ROOT, 'sw-precache.js');
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const missing = [...Object.values(CORE), ...Object.values(LAZY)].filter((f) => !existsSync(join(ROOT, f)));
  if (missing.length) { console.error('stamp: missing files: ' + missing.join(', ')); process.exit(1); }
  writeFileSync(out, render(build()));
  console.log('sw-precache.js written (core ' + build().coreHash + ', lazy ' + build().lazyHash + ')');
}
